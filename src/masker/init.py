"""Generating a starter ``masker.yaml`` from a reflected schema.

``masker init`` lists every table and every column. Columns whose name or
sampled values look like PII get a rule pre-filled and marked
``# SUGGESTED, review me``. Everything else is listed as a comment, so the file
stays valid YAML while making it obvious that those columns still need a
decision.
"""

from __future__ import annotations

import json
import re
from datetime import datetime, timezone
from typing import Any

import yaml

from masker.connect import redact_url
from masker.scan import NON_GATING_CATEGORIES, ScanResult, match_name
from masker.schema import ReflectedSchema

__all__ = ["render_starter_rules"]

_HEADER = """\
# masker.yaml -- generated by `masker init` at {timestamp}
# Source: {source}
#
# Every table and column in the source schema is listed below.
#
#   * A column with a `transformer:` was suggested from its name or its sampled
#     values. It is marked "# SUGGESTED, review me" -- suggestions are
#     heuristics, not judgements. Read each one.
#   * A column that appears only in a comment has NO rule and will be copied
#     verbatim. Either give it a transformer, or write `transformer: keep`
#     once you have decided it is safe. `masker scan` lists these for you.
#
# The key is never stored here. Export MASKER_SECRET_KEY, or point --key-file
# at a key file, before running.
#
# Masking reduces disclosure risk. It is not a legal guarantee of anonymity.

version: 1

settings:
  batch_size: 5000
  null_passthrough: true
  create_schema: true
  locale: en_US

tables:
"""


def render_starter_rules(
    schema: ReflectedSchema,
    scan: ScanResult,
    *,
    source_url: str = "",
    tables: list[str] | None = None,
) -> str:
    """Render a starter rules file covering the whole schema."""
    findings = {(finding.table, finding.column): finding for finding in scan.findings}
    selected = set(tables) if tables is not None else None
    parts: list[str] = [
        _HEADER.format(
            timestamp=datetime.now(timezone.utc).isoformat(timespec="seconds"),
            source=redact_url(source_url) if source_url else "<unknown>",
        )
    ]

    for group in schema.ordered_tables:
        for name in group:
            if selected is not None and name not in selected:
                continue
            parts.append(_render_table(name, schema, findings))

    rendered = "".join(parts)
    return rendered.rstrip("\n") + "\n"


def _render_table(
    name: str,
    schema: ReflectedSchema,
    findings: dict[tuple[str, str], Any],
) -> str:
    table = schema.tables[name]
    lines = [f"\n  {_yaml_name(name)}:\n", "    action: copy\n"]
    suggested: list[str] = []
    unruled: list[str] = []

    for column in table.columns:
        finding = findings.get((name, column.name))
        if finding is not None and finding.category not in NON_GATING_CATEGORIES:
            suggested.append(
                f"      {_yaml_name(column.name)}:\n"
                + _render_suggestion(finding.transformer, finding.params)
            )
        else:
            note = ""
            if finding is not None:
                note = f"  # {finding.category}: review the contents by hand"
            unruled.append(f"      # {column.name:<24} -- no rule (review me){note}\n")

    if suggested:
        lines.append("    columns:\n")
        lines.extend(suggested)
    else:
        lines.append("    columns: {}\n")
    if unruled:
        lines.append("\n")
        lines.extend(unruled)
    return "".join(lines)


def _render_suggestion(transformer: str, params: dict[str, Any]) -> str:
    """Render ``# SUGGESTED, review me`` plus the rule body, indented 8 spaces."""
    lines = ["        # SUGGESTED, review me\n"]
    body: dict[str, Any] = {"transformer": transformer}
    if params:
        body["params"] = params
    dumped = yaml.safe_dump(body, default_flow_style=False, sort_keys=False)
    for line in dumped.rstrip("\n").split("\n"):
        lines.append(f"        {line}\n")
    lines.append("\n")
    return "".join(lines)


def suggested_for(column_name: str) -> dict[str, Any] | None:
    """The suggested rule for one column name, or ``None``."""
    pattern = match_name(column_name)
    if pattern is None or pattern.category in NON_GATING_CATEGORIES:
        return None
    return {"transformer": pattern.transformer, "params": dict(pattern.params)}


def _yaml_name(name: str) -> str:
    if re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", name) and name.lower() not in {
        "yes",
        "no",
        "true",
        "false",
        "null",
        "on",
        "off",
    }:
        return name
    return json.dumps(name)
